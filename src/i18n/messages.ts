export type MessageKey = keyof Catalog;
export type MessageArgs<K extends MessageKey> = Catalog[K] extends (...args: infer P) => string ? P : [];
export type Translator = <K extends MessageKey>(key: K, ...args: MessageArgs<K>) => string;

export const catalogs = { 'zh-CN': zhCN, en } satisfies Record<Locale, Catalog>;

export function translate<K extends MessageKey>(
  locale: Locale,
  key: K,
  ...args: MessageArgs<K>
): string {
  const message = catalogs[locale][key];
  return typeof message === 'function'
    ? (message as unknown as (...parameters: MessageArgs<K>) => string)(...args)
    : message;
}
