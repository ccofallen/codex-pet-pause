import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const SOURCE = 'Generated by scripts/generate-android-cat-meow.mjs'

function chunk(name, payload) {
  const padding = payload.length % 2
  const result = Buffer.alloc(8 + payload.length + padding)
  result.write(name, 0, 4, 'ascii')
  result.writeUInt32LE(payload.length, 4)
  payload.copy(result, 8)
  return result
}

export function generateCatMeowWav() {
  const sampleRate = 22050
  const durationSeconds = 0.62
  const sampleCount = Math.floor(sampleRate * durationSeconds)
  const pcm = Buffer.alloc(sampleCount * 2)

  for (let index = 0; index < sampleCount; index += 1) {
    const time = index / sampleRate
    const progress = time / durationSeconds
    const attack = Math.min(1, time / 0.025)
    const release = Math.pow(Math.max(0, 1 - progress), 1.7)
    const envelope = attack * release
    const fundamental = 690 - (280 * progress) + (45 * Math.sin(progress * Math.PI))
    const phase = 2 * Math.PI * fundamental * time
    const voice =
      (0.66 * Math.sin(phase)) +
      (0.24 * Math.sin((phase * 2.03) + 0.3)) +
      (0.10 * Math.sin((phase * 3.94) + 0.8))
    const sample = Math.max(-1, Math.min(1, voice * envelope * 0.72))
    pcm.writeInt16LE(Math.round(sample * 32767), index * 2)
  }

  const format = Buffer.alloc(16)
  format.writeUInt16LE(1, 0)
  format.writeUInt16LE(1, 2)
  format.writeUInt32LE(sampleRate, 4)
  format.writeUInt32LE(sampleRate * 2, 8)
  format.writeUInt16LE(2, 12)
  format.writeUInt16LE(16, 14)

  const comment = Buffer.from(`${SOURCE}\0`, 'ascii')
  const info = Buffer.concat([Buffer.from('INFO', 'ascii'), chunk('ICMT', comment)])
  const body = Buffer.concat([chunk('fmt ', format), chunk('LIST', info), chunk('data', pcm)])
  const header = Buffer.alloc(12)
  header.write('RIFF', 0, 4, 'ascii')
  header.writeUInt32LE(body.length + 4, 4)
  header.write('WAVE', 8, 4, 'ascii')
  return Buffer.concat([header, body])
}

const scriptPath = fileURLToPath(import.meta.url)
if (resolve(process.argv[1] ?? '') === scriptPath) {
  const output = resolve(process.argv[2] ?? 'android/app/src/main/res/raw/cat_meow.wav')
  mkdirSync(dirname(output), { recursive: true })
  writeFileSync(output, generateCatMeowWav())
}
